package com.mesh.core

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyInfo
import android.security.keystore.KeyProperties
import java.math.BigInteger
import java.security.KeyFactory
import java.security.KeyPairGenerator
import java.security.KeyStore
import java.security.MessageDigest
import java.security.PrivateKey
import java.security.cert.X509Certificate
import java.util.Date
import javax.security.auth.x500.X500Principal

object IdentityStore {
    const val KEYSTORE_ALIAS = "mesh_identity"

    /**
     * Loads (or creates on first run) this device's TLS identity from the AndroidKeyStore.
     * Blocking — Keystore RSA-2048 generation can take seconds; call off the main thread.
     * [alias] is overridable so instrumented tests can create a second, distinct identity.
     */
    @Suppress("UNUSED_PARAMETER")
    fun loadOrCreate(context: Context, alias: String = KEYSTORE_ALIAS): Pair<X509Certificate, PrivateKey> {
        val keyStore = KeyStore.getInstance("AndroidKeyStore")
        keyStore.load(null)

        if (keyStore.containsAlias(alias)) {
            val privateKey = keyStore.getKey(alias, null) as? PrivateKey
            if (privateKey != null && isTlsCapable(privateKey)) {
                val cert = keyStore.getCertificate(alias) as X509Certificate
                return Pair(cert, privateKey)
            }
            // Key generated by an earlier build with a spec too narrow for TLS (see below):
            // replace it. Peers will see a new fingerprint and get the "certificate changed"
            // re-pair prompt, which is the correct, safe outcome.
            keyStore.deleteEntry(alias)
        }

        val generator = KeyPairGenerator.getInstance(KeyProperties.KEY_ALGORITHM_RSA, "AndroidKeyStore")
        generator.initialize(tlsKeySpec(alias))
        generator.generateKeyPair()

        val cert = keyStore.getCertificate(alias) as X509Certificate
        val privateKey = keyStore.getKey(alias, null) as PrivateKey
        return Pair(cert, privateKey)
    }

    /**
     * Key authorizations broad enough for every private-key operation the platform TLS
     * provider (Conscrypt) may perform with a Keystore-backed RSA key:
     *
     *  - TLS 1.2 / TLS 1.3 rsa_pkcs1_* signatures: Conscrypt hashes the handshake itself and
     *    asks the key for a raw "NONEwithRSA" PKCS#1 signature -> PURPOSE_SIGN + DIGEST_NONE +
     *    SIGNATURE_PADDING_RSA_PKCS1 (DIGEST_SHA256/384/512 kept for digest-in-key signing).
     *  - TLS 1.3 rsa_pss_rsae_* signatures (the default for TLS 1.3, Android 10+): Conscrypt
     *    applies the PSS encoding itself and asks the key for a raw RSA private-key operation
     *    ("RSA/ECB/NoPadding") -> PURPOSE_DECRYPT (and SIGN) + ENCRYPTION_PADDING_NONE +
     *    DIGEST_NONE. SIGNATURE_PADDING_RSA_PSS is listed for providers that sign PSS natively.
     *  - setRandomizedEncryptionRequired(false) is mandatory with ENCRYPTION_PADDING_NONE,
     *    otherwise key generation is rejected as violating IND-CPA.
     *
     * NOT verifiable in the build sandbox (no device/emulator): validate with the instrumented
     * PairingSessionTest on a real device (it handshakes TLS 1.2 and TLS 1.3 with two
     * Keystore-backed identities).
     */
    private fun tlsKeySpec(alias: String): KeyGenParameterSpec {
        val now = Date()
        val expiry = Date(now.time + 10L * 365 * 24 * 60 * 60 * 1000)
        return KeyGenParameterSpec.Builder(
            alias,
            KeyProperties.PURPOSE_SIGN or KeyProperties.PURPOSE_VERIFY or
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setKeySize(2048)
            .setDigests(
                KeyProperties.DIGEST_NONE,
                KeyProperties.DIGEST_SHA256,
                KeyProperties.DIGEST_SHA384,
                KeyProperties.DIGEST_SHA512)
            .setSignaturePaddings(
                KeyProperties.SIGNATURE_PADDING_RSA_PKCS1,
                KeyProperties.SIGNATURE_PADDING_RSA_PSS)
            .setEncryptionPaddings(
                KeyProperties.ENCRYPTION_PADDING_NONE,
                KeyProperties.ENCRYPTION_PADDING_RSA_PKCS1)
            .setRandomizedEncryptionRequired(false)
            .setUserAuthenticationRequired(false)
            .setCertificateSubject(X500Principal("CN=MeshDevice"))
            .setCertificateSerialNumber(BigInteger.ONE)
            .setCertificateNotBefore(now)
            .setCertificateNotAfter(expiry)
            .build()
    }

    /** True if an existing key carries the authorizations from [tlsKeySpec]. */
    private fun isTlsCapable(key: PrivateKey): Boolean = try {
        val info = KeyFactory.getInstance(key.algorithm, "AndroidKeyStore")
            .getKeySpec(key, KeyInfo::class.java)
        (info.purposes and KeyProperties.PURPOSE_DECRYPT) != 0 &&
            info.digests.contains(KeyProperties.DIGEST_NONE) &&
            info.encryptionPaddings.contains(KeyProperties.ENCRYPTION_PADDING_NONE)
    } catch (e: Exception) {
        false
    }

    /** Test helper: removes an identity (e.g. a temporary alias created by a test). */
    fun delete(alias: String) {
        val keyStore = KeyStore.getInstance("AndroidKeyStore")
        keyStore.load(null)
        if (keyStore.containsAlias(alias)) keyStore.deleteEntry(alias)
    }

    fun fingerprint(cert: X509Certificate): String {
        val hash = MessageDigest.getInstance("SHA-256").digest(cert.encoded)
        return hash.joinToString("") { "%02x".format(it) }
    }
}
